export const getRoleColorStyling = (color: string) => {
  switch (color) {
    case "blue":
      return "text-role-blue";
    case "purple":
      return "text-role-purple";
    case "green":
      return "text-role-green";
    case "cyan":
      return "text-role-cyan";
    case "yellow":
      return "text-role-yellow";
    case "red":
      return "text-role-red";
    case "orange":
      return "text-role-orange";
    case "magenta":
      return "text-role-magenta";
  }
};
